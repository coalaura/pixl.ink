function xyzToChromaticity(xyz) {
	const sum = xyz.x + xyz.y + xyz.z;

	if (sum < EPS_PRECISION) {
		return { x: 0, y: 0, z: 0 };
	}

	return {
		x: xyz.x / sum,
		y: xyz.y / sum,
		z: xyz.z / sum,
	};
}

function isPointInPolygon(point, polygon) {
	let inside = false;
	const x = point.x,
		y = point.y;

	for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
		const xi = polygon[i][0],
			yi = polygon[i][1];
		const xj = polygon[j][0],
			yj = polygon[j][1];

		if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
			inside = !inside;
		}
	}

	return inside;
}

export function isWithinHumanPerception(xyz) {
	// Basic validation: Y (luminance) must be non-negative
	if (xyz.y < 0) {
		return {
			isVisible: false,
			reason: "Negative luminance (impossible)",
		};
	}

	// Check for very dark colors (below human detection threshold)
	if (xyz.y < EPS_PRECISION) {
		return {
			isVisible: false,
			reason: "Too dark to perceive",
		};
	}

	// Check for extremely bright colors (beyond reasonable perception)
	if (xyz.y > 1) {
		return {
			isVisible: false,
			reason: "Extremely bright (may damage vision)",
		};
	}

	// Convert to chromaticity coordinates
	const chromaXYZ = xyzToChromaticity(xyz);

	// Check basic chromaticity constraints
	if (chromaXYZ.x < 0 || chromaXYZ.y < 0 || chromaXYZ.z < 0) {
		return {
			isVisible: false,
			reason: "Invalid chromaticity coordinates",
		};
	}

	const perceptualBoundary = [...SPECTRAL_LOCUS_XY],
		violetEnd = SPECTRAL_LOCUS_XY[0];

	perceptualBoundary.push(violetEnd);

	// Check if chromaticity point is within the boundary
	const chromaticityPoint = {
		x: chromaXYZ.x,
		y: chromaXYZ.y,
	};

	const isInsideBoundary = isPointInPolygon(chromaticityPoint, perceptualBoundary);

	if (!isInsideBoundary) {
		return {
			isVisible: false,
			reason: "Outside human visual gamut",
		};
	}

	// Additional check for the "impossible colors" region
	// Colors that are mathematically valid but don't correspond to real spectra
	if (chromaXYZ.y > 0.9 && chromaXYZ.x < 0.1) {
		return {
			isVisible: false,
			reason: "Impossible color (no corresponding spectrum)",
		};
	}

	return {
		isVisible: true,
		reason: "Within human perception",
	};
}
